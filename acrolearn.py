def embed(texts):
    out_vectors = []
    for i in range(0, len(texts), 100):
        batch = texts[i:i+100]
        success = False
        while not success:
            try:
                out = client.models.embed_content(model=EMBED_MODEL, contents=batch)
                out_vectors += [e.values for e in out.embeddings]
                success = True
            except Exception as e:
                if "429" in str(e) or "RESOURCE_EXHAUSTED" in str(e):
                    print("Rate limit hit. Sleeping for 15 seconds...")
                    time.sleep(15)
                else:
                    raise e
        # Optional delay to avoid hitting the rate limit between batches
        time.sleep(2)
    return out_vectors

